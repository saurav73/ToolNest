export const CATEGORIES = ['Text Tools', 'PDF Tools', 'Image Tools', 'Generators', 'Developer Tools', 'Business Tools', 'Email Tools'];

/** URL-friendly anchor id for a category, e.g. "PDF Tools" -> "pdf-tools". */
export function categoryId(cat) {
  return cat.toLowerCase().replace(/\s+/g, '-');
}

export function relatedTools(slug, count = 3) {
  const tool = TOOLS.find((t) => t.slug === slug);
  if (!tool) return TOOLS.slice(0, count);
  const same = TOOLS.filter((t) => t.slug !== slug && t.category === tool.category);
  const rest = TOOLS.filter((t) => t.slug !== slug && t.category !== tool.category);
  return [...same, ...rest].slice(0, count);
}
